function siteOrigin(): string {
  const explicit = process.env['NEXT_PUBLIC_SITE_ORIGIN']
  if (explicit !== undefined && explicit !== '') return explicit
  const vercel = process.env['VERCEL_PROJECT_PRODUCTION_URL']
  if (vercel !== undefined && vercel !== '') return `https://${vercel}`
  return 'http://localhost:3000'
}

/**
 * NOTE THE ABSENCE OF an `icons` KEY, WHICH IS DELIBERATE.
 *
 * Next merges the `app/icon.*` and `app/apple-icon.*` file conventions into the resolved
 * metadata only when `icons` is undefined — the merge is guarded by `if (!resolvedMetadata
 * .icons)`. Declaring the key here, even partially, silently DELETES every tag those files
 * would have produced. `favicon.ico` is special-cased and survives; nothing else does.
 *
 * So it is file conventions or `metadata.icons`, never both. This app uses the files:
 * `icon.svg`, `favicon.ico` and `apple-icon.png` all live in this directory and are
 * generated by `pnpm brand:assets`. `openGraph` and `manifest` are unaffected by that rule.
 */
export const metadata: Metadata = {
  /* Resolves the social card to an absolute URL. Read from the environment rather than
     hardcoded: `cloakcal.com` is registered but not yet attached to the project, so writing
     it here would point every unfurl at a host that currently fails its TLS handshake.
     Vercel sets VERCEL_PROJECT_PRODUCTION_URL to whatever the production domain actually is,
     which follows the apex the moment it IS attached. */
  metadataBase: new URL(siteOrigin()),
  // No `template` here. The four pages below already end their own titles with "— CloakCal",
  // so a template would render "Sign in — CloakCal — CloakCal".
  title: 'CloakCal',
  /*
   * SAYS WHAT IT IS, because a description is not a tagline. This was
   * 'Not everything is for everyone.' -- fine above a hero that explains itself, and the
   * only thing a search result or a link unfurl had to go on. Neither ever said the word
   * calendar.
   *
   * Bound by rule 1 like every other claim: what is encrypted is the CONTENT, and the
   * sentence says so rather than implying the whole event is sealed.
   */
  description:
    'A calendar that shows different people different amounts of the same event. Titles, places and notes are encrypted in your browser.',
  applicationName: 'CloakCal',
  manifest: '/manifest.webmanifest',
  openGraph: {
    type: 'website',
    siteName: 'CloakCal',
    title: 'CloakCal',
    description:
      'A calendar that shows different people different amounts of the same event. Titles, places and notes are encrypted in your browser.',
  },
  twitter: { card: 'summary_large_image' },
}

